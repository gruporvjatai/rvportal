-- PARTE B - despesas.categoria_id
--   * Adiciona categoria_id (FK) em public.despesas.
--   * Preenche (backfill) cada despesa existente com a categoria
--     correspondente, mapeando o texto antigo de `item`.
--   * A coluna `item` NAO e alterada (fica como historico/rollback).
--
-- CUIDADO: rode o backup ANTES:
--   CREATE TABLE public.despesas_backup_YYYYMMDD AS SELECT * FROM public.despesas;
--
-- IDEMPOTENTE (pode rodar quantas vezes quiser).
-- ============================================================

-- ---------- PARTE A: tabela de categorias de despesa ----------
CREATE TABLE IF NOT EXISTS public.categorias_despesas (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome text NOT NULL,
    criado_em timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS categorias_despesas_nome_uidx
    ON public.categorias_despesas (upper(nome));

ALTER TABLE public.categorias_despesas ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS rls_authenticated_all ON public.categorias_despesas;
CREATE POLICY rls_authenticated_all ON public.categorias_despesas
    FOR ALL TO authenticated USING (true) WITH CHECK (true);

GRANT SELECT, INSERT, UPDATE, DELETE ON public.categorias_despesas TO authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;


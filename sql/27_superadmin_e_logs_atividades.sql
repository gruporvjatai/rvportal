-- 27_superadmin_e_logs_atividades.sql
-- Categoria "superadmin" + registro de atividades do sistema (auditoria).
--
-- Contexto:
--   * usuarios.nivel_acesso passa a aceitar tambem 'superadmin'. Nao ha
--     constraint de dominio na coluna, entao nenhum ALTER de schema e
--     necessario para o novo valor.
--   * Nova tabela logs_atividades guarda o historico de TODAS as acoes
--     relevantes do sistema (criar/editar/excluir em qualquer tabela,
--     login/logout, etc.).
--   * Regras de superadmin (validadas tambem no banco, defesa em
--     profundidade):
--       1. Somente um superadmin pode atribuir a categoria 'superadmin'.
--       2. Somente um superadmin pode alterar um registro que ja e
--          superadmin.
--       3. Nao e possivel rebaixar o ULTIMO superadmin (anti-lockout).
--   * Leitura dos logs restrita a superadmin via RLS; insercao liberada
--     para qualquer usuario autenticado (todos geram log).
--
-- Afeta somente objetos SEM prefixo "jsp" (dominio do RV Portal).
-- Idempotente: pode ser executado mais de uma vez sem efeito colateral.
--
-- Bootstrap: ao final, promove 'maicon' a superadmin (1o superadmin).

-- ============================================================
-- 1) Funcao auxiliar: o usuario logado e superadmin?
--    SECURITY DEFINER para poder ler usuarios ignorando RLS.
--    - Em requisicoes da API (PostgREST) auth.jwt() traz as claims.
--    - No SQL Editor / migracoes auth.jwt() e NULL (contexto confiavel):
--      tratamos como autorizado para nao travar o bootstrap.
-- ============================================================
CREATE OR REPLACE FUNCTION public.e_superadmin()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT CASE
        WHEN auth.jwt() IS NULL THEN true
        ELSE EXISTS (
            SELECT 1
            FROM public.usuarios u
            WHERE lower(u.email) = lower(coalesce(auth.jwt()->>'email', ''))
              AND u.nivel_acesso = 'superadmin'
              AND coalesce(u.ativo, true) = true
        )
    END;
$$;

REVOKE ALL ON FUNCTION public.e_superadmin() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.e_superadmin() TO authenticated;

-- ============================================================
-- 2) Tabela de auditoria logs_atividades
-- ============================================================
CREATE TABLE IF NOT EXISTS public.logs_atividades (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    criado_em     timestamptz NOT NULL DEFAULT now(),
    usuario_id    text,
    usuario_nome  text,
    usuario_nivel text,
    modulo        text,
    acao          text,
    entidade_id   text,
    descricao     text,
    detalhes      jsonb,
    dispositivo   text
);

CREATE INDEX IF NOT EXISTS idx_logs_atividades_criado_em
    ON public.logs_atividades (criado_em DESC);
CREATE INDEX IF NOT EXISTS idx_logs_atividades_usuario
    ON public.logs_atividades (usuario_id);
CREATE INDEX IF NOT EXISTS idx_logs_atividades_modulo
    ON public.logs_atividades (modulo);

-- ============================================================
-- 3) RLS da tabela de auditoria
--    - INSERT: qualquer authenticated (todos registram atividade).
--    - SELECT/DELETE: somente superadmin.
--    - Sem policy de UPDATE: log e imutavel (append-only).
-- ============================================================
ALTER TABLE public.logs_atividades ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS logs_atividades_insert ON public.logs_atividades;
CREATE POLICY logs_atividades_insert ON public.logs_atividades
    FOR INSERT TO authenticated WITH CHECK (true);

DROP POLICY IF EXISTS logs_atividades_select_superadmin ON public.logs_atividades;
CREATE POLICY logs_atividades_select_superadmin ON public.logs_atividades
    FOR SELECT TO authenticated USING ((SELECT public.e_superadmin()));

DROP POLICY IF EXISTS logs_atividades_delete_superadmin ON public.logs_atividades;
CREATE POLICY logs_atividades_delete_superadmin ON public.logs_atividades
    FOR DELETE TO authenticated USING ((SELECT public.e_superadmin()));

GRANT SELECT, INSERT, DELETE ON public.logs_atividades TO authenticated;
REVOKE ALL ON public.logs_atividades FROM anon;

-- ============================================================
-- 4) Trigger de protecao da categoria superadmin em usuarios
-- ============================================================
CREATE OR REPLACE FUNCTION public.proteger_categoria_superadmin()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    sou_super boolean := public.e_superadmin();
    restantes int;
BEGIN
    -- Contexto de migracao/DDL (sem JWT): nao aplica as regras.
    IF auth.jwt() IS NULL THEN
        RETURN COALESCE(NEW, OLD);
    END IF;

    IF TG_OP = 'INSERT' THEN
        IF NEW.nivel_acesso = 'superadmin' AND NOT sou_super THEN
            RAISE EXCEPTION 'Somente um superadmin pode criar outro superadmin.';
        END IF;
        RETURN NEW;
    END IF;

    -- TG_OP = 'UPDATE'
    IF NEW.nivel_acesso = 'superadmin' AND NOT sou_super THEN
        RAISE EXCEPTION 'Somente um superadmin pode atribuir a categoria superadmin.';
    END IF;

    IF OLD.nivel_acesso = 'superadmin' AND NOT sou_super THEN
        RAISE EXCEPTION 'Somente um superadmin pode alterar um superadmin.';
    END IF;

    -- Anti-lockout: nao rebaixar o ultimo superadmin.
    IF OLD.nivel_acesso = 'superadmin' AND NEW.nivel_acesso <> 'superadmin' THEN
        SELECT count(*) INTO restantes
        FROM public.usuarios
        WHERE nivel_acesso = 'superadmin' AND id <> OLD.id;
        IF restantes = 0 THEN
            RAISE EXCEPTION 'Nao e possivel rebaixar o ultimo superadmin.';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_proteger_categoria_superadmin ON public.usuarios;
CREATE TRIGGER trg_proteger_categoria_superadmin
    BEFORE INSERT OR UPDATE ON public.usuarios
    FOR EACH ROW EXECUTE FUNCTION public.proteger_categoria_superadmin();

-- ============================================================
-- 5) Bootstrap: promove 'maicon' ao 1o superadmin
--    (roda com auth.jwt() NULL -> trigger libera).
-- ============================================================
UPDATE public.usuarios
SET nivel_acesso = 'superadmin'
WHERE lower(trim(login)) = 'maicon';

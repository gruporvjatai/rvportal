-- ============================================================
-- MIGRACAO 30: FILA DE COMANDOS DO ROBO (cobranca WhatsApp)
--
-- Por que existe: o ERP no celular/outro PC NAO consegue falar
-- com 127.0.0.1 do computador da Central. A nuvem tambem nao.
-- O clique grava um PEDIDO aqui. O robô local (porta 3010)
-- puxa o pedido, decide o número (travas) e manda o WhatsApp.
--
-- Esta tabela NÃO guarda telefone nem texto da mensagem.
-- Nao toca tabelas jsp_*.
--
-- COMO USAR: rode no SQL Editor do Supabase (idempotente).
-- ============================================================

create table if not exists public.robo_comandos (
    id            bigint generated by default as identity primary key,
    comando       text not null,
    cliente_id    bigint not null,
    confirm       boolean not null default false,
    status        text not null default 'queued',
    requested_by  text,
    claimed_at    timestamptz,
    processed_at  timestamptz,
    error         text,
    result        jsonb,
    created_at    timestamptz not null default now(),
    constraint robo_comandos_comando_chk check (comando in ('vencido')),
    constraint robo_comandos_status_chk check (status in ('queued', 'claimed', 'sent', 'failed')),
    constraint robo_comandos_confirm_chk check (confirm = true)
);

comment on table public.robo_comandos is
  'Pedidos de cobranca. O ERP so enfileira; o robo local executa.';

-- Um pedido pendente por cliente: clique duplo nao empilha envio.
create unique index if not exists robo_comandos_um_pendente
    on public.robo_comandos (comando, cliente_id)
    where status in ('queued', 'claimed');

create index if not exists robo_comandos_fila_idx
    on public.robo_comandos (status, created_at);

alter table public.robo_comandos enable row level security;

drop policy if exists robo_comandos_select on public.robo_comandos;
create policy robo_comandos_select on public.robo_comandos
    for select to authenticated using (true);

-- Navegador NAO insere/atualiza: so a Edge Function (service_role)
-- e o robo local (service_role) escrevem.
revoke insert, update, delete on public.robo_comandos from anon, authenticated;
grant select on public.robo_comandos to authenticated;
grant all on public.robo_comandos to service_role;
grant usage, select on sequence public.robo_comandos_id_seq to service_role;

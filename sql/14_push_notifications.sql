-- "hoje" no fuso do Brasil (o banco roda em UTC).
create or replace function private.hoje_brt()
returns date
language sql
stable
as $$
    select (now() at time zone 'America/Sao_Paulo')::date;
$$;

-- Envia um POST para a Edge Function "notify".
-- O segredo compartilhado fica no Vault sob o nome 'push_notify_secret'.
create or replace function private.notify(
    p_event text,
    p_ref   text,
    p_title text,
    p_body  text,
    p_url   text default null
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_secret text;
begin
    select decrypted_secret into v_secret
      from vault.decrypted_secrets
     where name = 'push_notify_secret'
     limit 1;

    perform net.http_post(
        url := 'https://lyieiqhkspbowsrlngvn.supabase.co/functions/v1/notify',
        headers := jsonb_build_object(
            'Content-Type', 'application/json',
            'x-webhook-secret', coalesce(v_secret, '')
        ),
        body := jsonb_build_object(
            'event_key', p_event,
            'ref_id',    p_ref,
            'title',     p_title,
            'body',      p_body,
            'url',       coalesce(p_url, '')
        ),
        timeout_milliseconds := 8000
    );
exception
    when others then
        -- Nunca derruba a transacao de negocio por falha de notificacao.
        raise warning 'private.notify falhou: % (%)', sqlerrm, p_event;
end;
$$;


-- 5.1) Nova venda finalizada (uma linha por item em "logs").
--      Gatilho a nivel de STATEMENT: agrupa por venda (id) e envia UMA vez.
create or replace function private.tg_notify_nova_venda()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    r record;
begin
    for r in
        select id, max(cliente_nome) as cliente_nome
          from new_rows
         where tipo = 'venda' and status = 'ATIVO'
         group by id
    loop
        perform private.notify(
            'nova_venda',
            'venda:' || r.id::text,
            'Nova venda finalizada',
            format('Venda #%s - %s', r.id, coalesce(r.cliente_nome, 'Consumidor')),
            '/sistema.html'
        );
    end loop;
    return null;
end;
$$;

drop trigger if exists trg_notify_nova_venda on public.logs;
create trigger trg_notify_nova_venda
    after insert on public.logs
    referencing new table as new_rows
    for each statement
    execute function private.tg_notify_nova_venda();

-- 5.2) Agenda de instalacao (agendada p/ hoje/amanha, e mudancas de status).
create or replace function private.tg_notify_agenda()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_cliente text;
    v_quando  text;
begin
    select cliente_nome into v_cliente
      from public.mdf_orcamentos
     where id = new.orcamento_id;

    -- Agendada para hoje ou amanha.
    if new.status = 'AGENDADO'
       and new.data_agendada is not null
       and new.data_agendada in (private.hoje_brt(), private.hoje_brt() + 1) then
        v_quando := case when new.data_agendada = private.hoje_brt() then 'hoje' else 'amanha' end;
        perform private.notify(
            'instalacao_proxima',
            'agenda:' || new.id::text || ':' || new.data_agendada::text || ':proxima',
            'Instalacao agendada',
            format('Instalacao de %s marcada para %s (%s).',
                   coalesce(v_cliente, 'cliente'), v_quando,
                   to_char(new.data_agendada, 'DD/MM')),
            '/sistema.html'
        );
    end if;

    -- Mudanca de status (reagendado/cancelado/concluido).
    if tg_op = 'UPDATE'
       and new.status is distinct from old.status
       and new.status in ('REAGENDADO', 'CANCELADO', 'CONCLUIDO') then
        perform private.notify(
            'instalacao_status',
            'agenda:' || new.id::text || ':' || new.status || ':' ||
                extract(epoch from now())::bigint::text,
            'Instalacao ' || lower(new.status),
            format('Instalacao de %s: status %s.',
                   coalesce(v_cliente, 'cliente'), new.status),
            '/sistema.html'
        );
    end if;

    return new;
end;
$$;

drop trigger if exists trg_notify_agenda on public.mdf_agenda;
create trigger trg_notify_agenda
    after insert or update on public.mdf_agenda
    for each row
    execute function private.tg_notify_agenda();

-- 5.3) Estoque baixo/zerado (disponivel = fisico - comprometido).
create or replace function private.tg_notify_estoque_baixo()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_disp numeric;
begin
    v_disp := coalesce(new.estoque_fisico, 0) - coalesce(new.estoque_comprometido, 0);
    if v_disp <= 10 then
        perform private.notify(
            'estoque_baixo',
            'estoque:' || new.id::text || ':' || private.hoje_brt()::text,
            case when v_disp <= 0 then 'Produto sem estoque' else 'Estoque baixo' end,
            format('%s: %s unidade(s) disponivel(is).', new.nome, trim(to_char(v_disp, 'FM999999990.##'))),
            '/sistema.html'
        );
    end if;
    return new;
end;
$$;

drop trigger if exists trg_notify_estoque_baixo on public.produtos;
create trigger trg_notify_estoque_baixo
    after insert or update of estoque_fisico, estoque_comprometido on public.produtos
    for each row
    execute function private.tg_notify_estoque_baixo();


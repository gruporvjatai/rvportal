-- MIGRACAO 14: NOTIFICACOES PUSH (Web Push / VAPID)
--
-- Objetivo:
--   * Disparar notificacoes push (somente push, sem sino interno)
--     para os usuarios do app quando eventos importantes ocorrem.
--   * As "regras" de o-que-notificar sao definidas pelo ADMIN
--     (nao por usuario). Ver tabela notification_settings.
--   * Segmentar o publico por nivel de acesso (admin/vendedor/
--     instalador). Por padrao: admin recebe tudo.
--
-- Eventos suportados:
--   nova_venda          - venda finalizada
--   conta_receber       - titulos a receber vencendo hoje/atrasados
--   conta_pagar         - despesas pendentes vencendo hoje/atrasadas
--   instalacao_proxima  - instalacao agendada para hoje/amanha
--   instalacao_status   - instalacao reagendada/cancelada/concluida
--   estoque_baixo       - produto com estoque disponivel <= 10
--   folha_gerada        - folha de pagamento gerada
--   vale_lancado        - vale lancado para uma equipe
--   folha_pendente      - folha de pagamento pendente (varredura diaria)
--
-- COMO USAR:
--   1) Rode este arquivo no Supabase SQL Editor (idempotente).
--   2) Crie o segredo compartilhado no Vault (ver rodape do arquivo).
--   3) Publique a Edge Function "notify" e configure os secrets.
--
-- IMPORTANTE: toca SOMENTE tabelas publicas SEM o prefixo "jsp_".
-- ============================================================


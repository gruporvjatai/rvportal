-- 6.1) Contas a receber vencendo hoje / atrasadas.
create or replace function private.cron_scan_receber()
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_hoje   integer;
    v_atras  integer;
    v_total  numeric;
begin
    select
        count(*) filter (where nullif(vencimento,'')::date = private.hoje_brt()),
        count(*) filter (where nullif(vencimento,'')::date < private.hoje_brt()),
        coalesce(sum(valor_total) filter (
            where nullif(vencimento,'')::date <= private.hoje_brt()), 0)
      into v_hoje, v_atras, v_total
      from public.logs
     where tipo in ('venda', 'receita')
       and status = 'ATIVO'
       and coalesce(status_financeiro, '') in ('A RECEBER', 'PENDENTE')
       and nullif(vencimento, '') is not null
       and nullif(vencimento, '')::date <= private.hoje_brt();

    if (v_hoje + v_atras) > 0 then
        perform private.notify(
            'conta_receber',
            'receber:' || private.hoje_brt()::text,
            'Contas a receber',
            format('%s vencendo hoje e %s atrasada(s). Total: R$ %s.',
                   v_hoje, v_atras, trim(to_char(v_total, 'FM999999990.00'))),
            '/sistema.html'
        );
    end if;
end;
$$;

-- 6.2) Contas a pagar pendentes vencendo hoje / atrasadas.
create or replace function private.cron_scan_pagar()
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_hoje  integer;
    v_atras integer;
    v_total numeric;
begin
    select
        count(*) filter (where nullif(data,'')::date = private.hoje_brt()),
        count(*) filter (where nullif(data,'')::date < private.hoje_brt()),
        coalesce(sum(coalesce(custo,0) * coalesce(quantidade,1)) filter (
            where nullif(data,'')::date <= private.hoje_brt()), 0)
      into v_hoje, v_atras, v_total
      from public.despesas
     where status = 'PENDENTE'
       and nullif(data, '') is not null
       and nullif(data, '')::date <= private.hoje_brt();

    if (v_hoje + v_atras) > 0 then
        perform private.notify(
            'conta_pagar',
            'pagar:' || private.hoje_brt()::text,
            'Contas a pagar',
            format('%s vencendo hoje e %s atrasada(s). Total: R$ %s.',
                   v_hoje, v_atras, trim(to_char(v_total, 'FM999999990.00'))),
            '/sistema.html'
        );
    end if;
end;
$$;

-- 6.3) Folhas pendentes.
create or replace function private.cron_scan_folha_pendente()
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_qtd integer;
begin
    select count(*) into v_qtd
      from public.folhas
     where status = 'PENDENTE';

    if v_qtd > 0 then
        perform private.notify(
            'folha_pendente',
            'folha_pend:' || private.hoje_brt()::text,
            'Folha pendente',
            format('%s folha(s) de pagamento pendente(s).', v_qtd),
            '/sistema.html'
        );
    end if;
end;
$$;

-- 6.4) Limpeza do log de idempotencia (mantem 60 dias).
create or replace function private.cron_cleanup_notification_log()
returns void
language sql
security definer
set search_path = public, pg_temp
as $$
    delete from public.notification_log where created_at < now() - interval '60 days';
$$;

-- Agendamentos (horario em UTC). 10:00 UTC = 07:00 America/Sao_Paulo.
do $$
declare
    j text;
begin
    foreach j in array array[
        'notify_conta_receber', 'notify_conta_pagar',
        'notify_folha_pendente', 'notify_cleanup'
    ]
    loop
        if exists (select 1 from cron.job where jobname = j) then
            perform cron.unschedule(j);
        end if;
    end loop;
end;
$$;

select cron.schedule('notify_conta_receber', '0 10 * * *', $$ select private.cron_scan_receber(); $$);
select cron.schedule('notify_conta_pagar',   '0 10 * * *', $$ select private.cron_scan_pagar(); $$);
select cron.schedule('notify_folha_pendente','0 10 * * *', $$ select private.cron_scan_folha_pendente(); $$);
select cron.schedule('notify_cleanup',       '30 3 * * *', $$ select private.cron_cleanup_notification_log(); $$);


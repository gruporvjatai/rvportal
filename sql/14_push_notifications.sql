-- 1.1) Inscricoes push (uma por dispositivo/navegador).
create table if not exists public.push_subscriptions (
    id           bigint generated by default as identity primary key,
    user_email   text not null,
    user_id      uuid,
    endpoint     text not null unique,
    p256dh       text not null,
    auth         text not null,
    user_agent   text,
    created_at   timestamptz not null default now(),
    last_seen_at timestamptz not null default now()
);
create index if not exists push_subscriptions_user_email_idx
    on public.push_subscriptions (user_email);

-- 1.2) Preferencias de notificacao (globais, definidas pelo admin).
create table if not exists public.notification_settings (
    event_key  text primary key,
    enabled    boolean not null default true,
    roles      text[]  not null default array['admin']::text[],
    updated_at timestamptz not null default now()
);

-- 1.3) Log de envio (idempotencia: nao repetir o mesmo evento/pessoa).
create table if not exists public.notification_log (
    id         bigint generated by default as identity primary key,
    event_key  text not null,
    ref_id     text not null,
    user_email text not null,
    created_at timestamptz not null default now(),
    constraint notification_log_unique unique (event_key, ref_id, user_email)
);
create index if not exists notification_log_created_at_idx
    on public.notification_log (created_at);

-- ------------------------------------------------------------------
-- 2) RLS
-- ------------------------------------------------------------------
alter table public.push_subscriptions   enable row level security;
alter table public.notification_settings enable row level security;
alter table public.notification_log      enable row level security;

-- 2.1) push_subscriptions: cada usuario so enxerga/gerencia as S SUAS inscricoes.
drop policy if exists push_subscriptions_own on public.push_subscriptions;
create policy push_subscriptions_own on public.push_subscriptions
    for all to authenticated
    using (lower(user_email) = lower(auth.jwt() ->> 'email'))
    with check (lower(user_email) = lower(auth.jwt() ->> 'email'));

-- 2.2) notification_settings: qualquer autenticado LÊ; somente admin ESCREVE.
drop policy if exists notification_settings_read on public.notification_settings;
create policy notification_settings_read on public.notification_settings
    for select to authenticated using (true);

drop policy if exists notification_settings_admin_write on public.notification_settings;
create policy notification_settings_admin_write on public.notification_settings
    for all to authenticated
    using (
        exists (
            select 1 from public.usuarios u
            where lower(u.email) = lower(auth.jwt() ->> 'email')
              and u.nivel_acesso = 'admin'
        )
    )
    with check (
        exists (
            select 1 from public.usuarios u
            where lower(u.email) = lower(auth.jwt() ->> 'email')
              and u.nivel_acesso = 'admin'
        )
    );

-- 2.3) notification_log: leitura autenticada; escrita apenas via service_role.
drop policy if exists notification_log_read on public.notification_log;
create policy notification_log_read on public.notification_log
    for select to authenticated using (true);

-- (re)garante privilegios explicitos (idempotente).
grant select, insert, update, delete on public.push_subscriptions  to authenticated;
grant select, insert, update, delete on public.notification_settings to authenticated;
grant select on public.notification_log to authenticated;
grant usage, select on all sequences in schema public to authenticated;


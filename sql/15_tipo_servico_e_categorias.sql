    ('ACESSÓRIOS'), ('DIVERSOS'), ('MADERITE'), ('PALANQUE'), ('CUMARU')
ON CONFLICT DO NOTHING;

-- Normaliza categorias ja cadastradas nos produtos (remove \r\n/espacos, MAIUSCULA).
UPDATE public.produtos
   SET categoria = upper(btrim(regexp_replace(coalesce(categoria, ''), '\s+', ' ', 'g')));

